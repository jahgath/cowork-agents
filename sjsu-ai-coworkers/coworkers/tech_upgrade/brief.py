"""Render the Daily Technical Learning Brief (Markdown)."""
from __future__ import annotations

from ..taxonomy import label

MIN_SESSION, MAX_SESSION = 15, 20
REFLECTION_MIN = 2


def plan_session(cards: list[dict], target: int = 18) -> list[int]:
    """Allocate minutes so the whole session (reading + 2-min reflection) lands in 15-20 min."""
    target = max(MIN_SESSION, min(MAX_SESSION, target))
    budget = target - REFLECTION_MIN
    raw = [c.get("reading_minutes", 6) for c in cards]
    total = sum(raw) or 1
    alloc = [max(3, round(budget * r / total)) for r in raw]
    # fix rounding drift on the top-ranked article
    alloc[0] += budget - sum(alloc)
    return alloc


def render_brief(date: str, profile: dict, cards: list[dict], meta: dict) -> str:
    minutes = plan_session(cards, profile.get("daily_reading_minutes", 18))
    total = sum(minutes) + REFLECTION_MIN
    lines = [
        f"# Daily Technical Learning Brief — {date}",
        "",
        f"For {profile.get('name', 'you')} · goal: {profile.get('career_goal')} · session: {total} minutes",
        "",
        f"Today's focus: {', '.join(dict.fromkeys(label(c['primary_topic']) for c in cards))}.",
        "",
        "## Reading plan",
        "",
        "| # | Article | Source | Published | Minutes |",
        "|---|---------|--------|-----------|---------|",
    ]
    for i, (c, m) in enumerate(zip(cards, minutes), 1):
        lines.append(f"| {i} | [{c['title']}]({c['url']}) | {c['source']} | {c.get('published') or 'n/a'} | {m} |")
    lines.append(f"| | Reflection: answer the three check questions | | | {REFLECTION_MIN} |")
    lines.append("")

    for i, (c, m) in enumerate(zip(cards, minutes), 1):
        age = c.get("age_days")
        freshness = "" if age is None else (" (published this week)" if age <= 7 else f" ({age} days old — selected as a foundational read)" if age > 30 else "")
        lines += [
            f"## {i}. {c['title']}",
            "",
            f"Source: {c['source']} ({c['org']}) · Published: {c.get('published') or 'n/a'}{freshness} · "
            f"Topic: {label(c['primary_topic'])} · Level: {c.get('difficulty', 'intermediate')} · ~{m} min",
            "",
            f"URL: {c['url']}",
            "",
            f"Summary. {c['summary']}",
            "",
            "Key technical insights:",
            "",
            *[f"- {s}" for s in c.get("key_insights", [])],
            "",
            "Takeaways:",
            "",
            *[f"- {s}" for s in c.get("takeaways", [])],
            "",
            f"How this builds your knowledge. {c.get('why_it_matters', '')}",
            "",
            f"Career link. {c.get('career_link', '')}",
            "",
            f"Check question. {c.get('quiz_question', '')}",
            "",
            f"Why it was picked: score {c['score']:.2f} — " + ", ".join(
                f"{k.replace('_', ' ')} {v:.2f}" for k, v in c.get("breakdown", {}).items()),
            "",
        ]

    lines += [
        "## After reading",
        "",
        "Rate each article so tomorrow's picks adapt to you:",
        "",
        "```",
        *[f"python -m coworkers.cli rate \"{c['url']}\" <1-5>" for c in cards],
        "```",
        "",
        "---",
        f"Generated by DailyTechUpgradeAgent · mode: {meta.get('mode')} · summarizer: {meta.get('llm')} · "
        f"candidates scanned: {meta.get('n_candidates')} · recency window: {meta.get('window_days')} days",
    ]
    if meta.get("errors"):
        lines += ["", f"Sources unavailable this run: {len(meta['errors'])} (see run log)."]
    return "\n".join(lines) + "\n"
